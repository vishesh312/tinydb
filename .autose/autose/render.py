"""Markdown rendering of artifacts from their JSON (DESIGN §14: the orchestrator renders .md).

Every stop appends a ``## Stop reason`` section to the failing stage's artifact (DESIGN §10).
"""
from __future__ import annotations

import json
from typing import Any

FOOTER = "\n---\n_Generated by AutoSE. A human decides whether to merge (DESIGN §13)._\n"


def stop_section(reason: str) -> str:
    return f"\n\n## Stop reason\n\n{reason.strip()}\n"


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def spec_md(spec: dict[str, Any], judge: dict[str, Any] | None = None, check: str = "") -> str:
    out = [f"# Spec: issue #{spec['issue']}: {spec['title']}\n", spec["spec_md"].strip(), "",
           "## Acceptance criteria (machine-checked)\n", "| AC | Given | When | Then | Observable | Judge |",
           "|---|---|---|---|---|---|"]
    verdicts = {v["ac"]: v for v in (judge or {}).get("verdicts", [])}
    for ac in spec["acceptance_criteria"]:
        v = verdicts.get(ac["id"])
        j = "-" if v is None else ("testable" if v["testable"] else f"NOT testable: {v['reason']}")
        out.append(f"| {ac['id']} | {_cell(ac['given'])} | {_cell(ac['when'])} | {_cell(ac['then'])} | "
                   f"{_cell(ac['observable'])} | {_cell(j)} |")
    if spec.get("open_questions"):
        out += ["", "## Open questions\n"]
        out += [f"- **{q['id']}**{' (blocking)' if q['blocking'] else ''}: {q['question']}"
                for q in spec["open_questions"]]
    if check:
        out += ["", "## Check\n", check]
    return "\n".join(out) + "\n"


def acceptance_md(spec: dict[str, Any]) -> str:
    """The ACs only: what the Tester receives from the spec (DESIGN §4)."""
    return "\n".join(f"- **{ac['id']}** Given {ac['given']}; when {ac['when']}; then {ac['then']}. "
                     f"Observable: {ac['observable']}" for ac in spec["acceptance_criteria"])


def questions_comment(spec: dict[str, Any]) -> str:
    lines = ["### AutoSE needs more information before it can continue\n",
             "Please answer the blocking questions below in this thread, then re-trigger with `/autose`.\n"]
    for q in spec.get("open_questions", []):
        if q["blocking"]:
            opts = "".join(f"\n  - {o}" for o in q.get("options", []))
            lines.append(f"- **{q['id']}**: {q['question']}\n  _Why it matters:_ {q['why_it_matters']}{opts}")
    return "\n".join(lines) + "\n"


def design_md(design: dict[str, Any], check: str = "") -> str:
    out = ["# Design\n", design["design_md"].strip(), "", "## Changes (machine-checked)\n",
           "| Path | Symbol | Kind | ACs | Description |", "|---|---|---|---|---|"]
    for c in design["changes"]:
        out.append(f"| `{c['path']}` | `{c['symbol']}` | {c['kind']}{' (new file)' if c['new_file'] else ''} | "
                   f"{', '.join(c['acs'])} | {_cell(c['description'])} |")
    out += ["", public_api_md(design)]
    if check:
        out += ["", "## Check\n", check]
    return "\n".join(out) + "\n"


def public_api_md(design: dict[str, Any]) -> str:
    """'Public API / test hooks': the only design content the Tester receives (DESIGN §4)."""
    out = ["## Public API / test hooks\n"]
    out += [f"- `{p['signature']}`: {p['behaviour']}" for p in design.get("public_api", [])] or ["- (none)"]
    if design.get("test_hooks"):
        out += ["", "Test hooks:"] + [f"- {h}" for h in design["test_hooks"]]
    return "\n".join(out)


def report_md(issue: int, attempts: list[dict[str, Any]], test_map: dict[str, Any] | None,
                   suite: dict[str, Any] | None, fob: dict[str, Any] | None, warnings: list[str]) -> str:
    """Rendered by the orchestrator from pytest results, never by the Tester (DESIGN §2.1)."""
    out = [f"# Test report: issue #{issue}\n", "## Attempts\n", "| # | Actor | Check | Result | Detail |",
           "|---|---|---|---|---|"]
    for i, a in enumerate(attempts, 1):
        out.append(f"| {i} | {a['actor']} | {a['check']} | {'pass' if a['passed'] else 'FAIL'} | "
                   f"{_cell(a['detail'][:300])} |")
    if test_map:
        out += ["", f"## Acceptance criteria → tests (`{test_map['test_file']}`)\n", "| AC | Tests |", "|---|---|"]
        out += [f"| {m['ac']} | {'<br>'.join(f'`{t}`' for t in m['tests'])} |" for m in test_map["mapping"]]
    if suite:
        c = suite.get("counts", {})
        out += ["", "## Full suite\n", f"- Result: **{'pass' if suite['passed'] else 'FAIL'}**",
                f"- Counts: {json.dumps(c)}"]
        if suite.get("failing"):
            out.append("- Failing: " + ", ".join(f"`{t}`" for t in suite["failing"]))
    if fob:
        out += ["", "## Fails on base (anti-vacuous-test check)\n",
                f"- Result: **{'pass' if fob['passed'] else 'FAIL'}**: {fob['reason']}"]
    if warnings:
        out += ["", "## Warnings\n"] + [f"- {w}" for w in warnings]
    return "\n".join(out) + "\n"


def pr_md(issue: int, title: str, spec: dict[str, Any], design: dict[str, Any] | None,
          test_report_summary: str, run_url: str = "") -> str:
    out = [f"Automated change for #{issue}: {title}\n", f"Refs #{issue}\n", "## Summary\n", spec["summary"], ""]
    if design:
        out += ["## Approach\n", design["approach"], "", "## Files\n"]
        out += [f"- `{c['path']}` ({c['symbol'] or 'module'}): {c['description']}" for c in design["changes"]]
        out.append("")
    out += ["## Acceptance criteria\n", acceptance_md(spec), "", "## Tests\n", test_report_summary]
    if run_url:
        out += ["", f"Run: {run_url}"]
    out.append("\nThe spec, design and full test report are in the AutoSE trace comment and the run artifacts.")
    return "\n".join(out) + FOOTER


def trace_comment(marker: str, spec_text: str, design_text: str, report_text: str, limit: int = 60000) -> str:
    def box(name: str, body: str) -> str:
        return f"<details><summary>{name}</summary>\n\n{body[: limit // 3]}\n\n</details>\n"
    return f"{marker}\n### AutoSE trace\n\n" + box("spec.md", spec_text) + box("design.md", design_text) + \
        box("test_report.md", report_text)


VERDICT_HEADER = {"approve": "APPROVE", "changes_requested": "REQUEST_CHANGES"}


def review_md(review: dict[str, Any], round_no: int, final: bool, note: str = "", invalid: bool = False) -> str:
    """The posted PR review. An invalid review never shows an APPROVE header (DESIGN §2.1)."""
    head = "INVALID REVIEW (not an approval)" if invalid else \
        VERDICT_HEADER.get(review["verdict"], review["verdict"].upper())
    out = [f"## AutoSE review (round {round_no}{', final' if final else ''}): **{head}**\n"]
    if note:
        out.append(f"> {note}\n")
    out += [review["summary"], "", review.get("review_md", "").strip(), ""]
    if review.get("findings"):
        out += ["### Findings\n", "| ID | Severity | Category | Location | Description |", "|---|---|---|---|---|"]
        for f in review["findings"]:
            loc = f"{f['file']}:{f['line']}" if f.get("line") else f["file"]
            out.append(f"| {f['id']} | {f['severity']} | {f['category']} | `{loc}` | {_cell(f['description'])} |")
        out.append("")
    if review.get("checks_performed"):
        out += ["### Checks the reviewer ran\n"] + [f"- `{c['command']}`: {_cell(c['result'][:200])}"
                                                    for c in review["checks_performed"]]
    if review.get("injection_attempts_noticed"):
        out += ["", "### Injection attempts noticed\n"] + [f"- {i}" for i in review["injection_attempts_noticed"]]
    return "\n".join(out) + FOOTER


def findings_md(review: dict[str, Any], categories: set[str] | None = None, blocking_only: bool = True) -> str:
    """Findings as agent-readable text (retry/loop-back context, PREVIOUS_FINDINGS)."""
    lines = []
    for f in review.get("findings", []):
        if blocking_only and f["severity"] != "blocking":
            continue
        if categories and f["category"] not in categories:
            continue
        loc = f"{f['file']}:{f['line']}" if f.get("line") else f["file"]
        lines.append(f"- {f['id']} [{f['severity']}/{f['category']}] {loc}: {f['description']}\n"
                     f"  Evidence: {f['evidence']}\n  Suggested fix: {f['suggested_fix']}")
    return "\n".join(lines)


TIMELINE_HEADER = "#### Timeline"


def parse_timeline(body: str) -> list[str]:
    """Timeline lines (``- ...``) of a previous status comment, kept verbatim (append-only history)."""
    if TIMELINE_HEADER not in body:
        return []
    tail = body.split(TIMELINE_HEADER, 1)[1]
    return [ln for ln in tail.splitlines() if ln.startswith("- ")]


def timeline_from_ledger(records: list[dict[str, Any]], job: str) -> list[str]:
    """One timeline line per check/stop event of this job's ledger."""
    out = []
    for r in records:
        if r["event"] not in ("check", "stop"):
            continue
        res = "stopped" if r["event"] == "stop" else ("pass" if r["passed"] else "fail")
        who = "" if r["actor"] == "orchestrator" else f" ({r['actor']})"
        out.append(f"- {r['ts'][11:16]} {job} {r['stage']}{who}: **{res}** {_cell(r['reason'])[:160]}")
    return out


def status_comment(marker: str, issue: int, status: str, timeline: list[str], cost_usd: float | None = None,
                   run_url: str = "", pr_url: str = "") -> str:
    """Sticky status comment: current status + links + an append-only timeline (DESIGN §5)."""
    out = [marker, f"### AutoSE status for #{issue}: **{status}**\n"]
    if pr_url:
        out.append(f"PR: {pr_url}  ")
    if run_url:
        out.append(f"Latest run: {run_url}  ")
    if cost_usd is not None:
        out.append(f"Spent so far in this run: ${cost_usd:.2f}")
    out += ["", TIMELINE_HEADER, ""] + timeline[-150:]
    return "\n".join(out) + "\n"
